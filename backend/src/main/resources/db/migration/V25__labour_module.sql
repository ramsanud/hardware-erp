-- OWNER's V1 CROSS JOIN grant only ran once, against whatever permission
-- rows existed at that time - it does NOT retroactively pick up permission
-- codes added by a later migration. Every module added after V1 must grant
-- OWNER explicitly here too, exactly as V18 (project management) does.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM role r JOIN permission p ON p.permission_code IN ('LABOUR_VIEW', 'LABOUR_MANAGE')
WHERE r.role_code = 'OWNER';

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM role r JOIN permission p ON p.permission_code IN ('LABOUR_VIEW', 'LABOUR_MANAGE')
WHERE r.role_code = 'MANAGER';

