    'CUSTOMER', 'SUPPLIER', 'PRODUCT', 'CATEGORY', 'BRAND',
    'INVOICE', 'QUOTATION', 'PURCHASE', 'PROJECT',
    'SALES_ORDER', 'DELIVERY_CHALLAN', 'CREDIT_NOTE'
));

