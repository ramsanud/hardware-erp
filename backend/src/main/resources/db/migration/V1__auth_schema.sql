-- =====================================================================
-- MODULE 1 : AUTHENTICATION, USERS, ROLES, PERMISSIONS
-- Target engine: PostgreSQL 14+ (developed and tested against 16)
-- Single shop. No tenant_id anywhere.
--
-- Migrated from MySQL 8 under CR-014. Table and column names are unchanged;
-- only engine-specific syntax and two collation-driven guarantees differ.
