--    on documents); BRANCH_MANAGE and BACKUP_MANAGE owner-only;
--    STOCK_TRANSFER_MANAGE owner + manager. Insights reuse REPORT_VIEW.
-- ---------------------------------------------------------------------
INSERT INTO permission (permission_code, permission_name, description, module_code, display_order) VALUES
 ('BRANCH_VIEW', 'View branches', 'See the shop''s branches and per-branch stock.', 'INVENTORY', 60),
 ('BRANCH_MANAGE', 'Manage branches', 'Create and edit branches and assign users to them.', 'INVENTORY', 61),
 ('STOCK_TRANSFER_MANAGE', 'Transfer stock between branches', 'Record a stock transfer from one branch to another.', 'INVENTORY', 62),
 ('BACKUP_MANAGE', 'Manage backups', 'Take and download backups of the shop''s data.', 'SETTINGS', 90);

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM role r JOIN permission p ON p.permission_code = 'BRANCH_VIEW'
WHERE r.role_code IN ('OWNER', 'MANAGER', 'ACCOUNTANT', 'STAFF');

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM role r JOIN permission p ON p.permission_code = 'STOCK_TRANSFER_MANAGE'
WHERE r.role_code IN ('OWNER', 'MANAGER');

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id
FROM role r JOIN permission p ON p.permission_code IN ('BRANCH_MANAGE', 'BACKUP_MANAGE')
WHERE r.role_code = 'OWNER';

