-- ---------------------------------------------------------------------
-- 5. A row inserted without a branch belongs to MAIN - by definition the
--    branch every unattributed row was backfilled onto above. Application
--    code always sets branch_id explicitly (BranchContext); this covers
--    the dev/test seed scripts (V9xx, written before branches existed and
--    never edited - rule 1) and any future direct SQL.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION branch_default_main() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.branch_id IS NULL THEN
        SELECT b.branch_id INTO NEW.branch_id FROM branch b
        WHERE b.tenant_id = NEW.tenant_id AND b.is_main;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stock_movement_branch_default BEFORE INSERT ON stock_movement
    FOR EACH ROW EXECUTE FUNCTION branch_default_main();
CREATE TRIGGER trg_invoice_branch_default BEFORE INSERT ON invoice
    FOR EACH ROW EXECUTE FUNCTION branch_default_main();
CREATE TRIGGER trg_purchase_branch_default BEFORE INSERT ON purchase
    FOR EACH ROW EXECUTE FUNCTION branch_default_main();

-- A tenant registered after this migration needs its MAIN branch too;
-- TenantRegistrationServiceImpl creates it, and this trigger guarantees it
-- for a tenant row inserted by seed or SQL.
CREATE OR REPLACE FUNCTION tenant_create_main_branch() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO branch (tenant_id, branch_code, branch_name, address_line1, city, state_code, pincode, phone, is_main, status, created_at)
    VALUES (NEW.tenant_id, 'MAIN', NEW.name, NEW.address_line1, NEW.city, NEW.state_code, NEW.pincode, NEW.phone, TRUE, 'ACTIVE', now())
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_tenant_main_branch AFTER INSERT ON tenant
    FOR EACH ROW EXECUTE FUNCTION tenant_create_main_branch();
