WHERE r.role_code = 'OWNER' AND p.permission_code IN
    ('PROJECT_VIEW', 'PROJECT_MANAGE', 'PROJECT_MATERIAL_VIEW', 'PROJECT_MATERIAL_MANAGE');

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id FROM role r CROSS JOIN permission p
WHERE r.role_code = 'MANAGER' AND p.permission_code IN
    ('PROJECT_VIEW', 'PROJECT_MANAGE', 'PROJECT_MATERIAL_VIEW', 'PROJECT_MATERIAL_MANAGE');

INSERT INTO role_permission (role_id, permission_id)
SELECT r.role_id, p.permission_id FROM role r CROSS JOIN permission p
WHERE r.role_code = 'ACCOUNTANT' AND p.permission_code IN ('PROJECT_VIEW', 'PROJECT_MATERIAL_VIEW');

INSERT INTO role_permission (role_id, permission_id)
